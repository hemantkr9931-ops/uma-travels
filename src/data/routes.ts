export function getRouteBySlug(originSlug: string, destinationSlug: string): Route | undefined {
  return ALL_ROUTES.find(
    (r) => r.originSlug === originSlug && r.destinationSlug === destinationSlug
  );
}

/**
 * Returns all routes involving a city — both outgoing and incoming, deduplicated.
 */
export function getAllRoutesForCity(citySlug: string): Route[] {
  const outgoing = getRoutesByOrigin(citySlug);
  const incoming = getRoutesByDestination(citySlug);
  const combined = [...outgoing, ...incoming];
  const seen = new Set<string>();
  return combined.filter((r) => {
    if (seen.has(r.id)) return false;
    seen.add(r.id);
    return true;
  });
}

/**
 * Returns all published routes involving a given state (either origin or destination in state).
 */
export function getRoutesForState(stateSlug: string): Route[] {
  return ALL_ROUTES.filter((r) => {
    if (r.status !== 'published') return false;
    const origin = getLocationBySlug(r.originSlug);
    const dest = getLocationBySlug(r.destinationSlug);
    return origin?.stateSlug === stateSlug || dest?.stateSlug === stateSlug;
  });
}

