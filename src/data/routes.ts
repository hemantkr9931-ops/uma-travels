// ─── ROUTE FARE HELPERS ───────────────────────────────────────────────────────
// Route pages, cards and SEO content must all resolve fares through these
// helpers so a route's quoted price stays identical everywhere it appears.
//   • A route with `startingFareOneWay` uses that exact sedan price.
//   • Higher vehicle categories are derived from the sedan fare using the
//     vehicle per-km ratio, so Ertiga < Carens < Innova < Tempo — always.
//   • Routes without a fixed fare fall back to the distance-based engine.

/**
 * Single authoritative source for route one-way fare calculations.
 * Exactly synchronized with EnhancedBookingForm and Fare Calculator (/api/places/route/):
 * - Sedan: ₹21/km (or ₹14/km * 2 for >200km non-Kolkata)
 * - Ertiga: ₹26/km (or ₹20/km * 2 for >200km non-Kolkata)
 * - Innova: ₹35/km (or ₹35/km * 2 for >200km non-Kolkata)
 */
export function getRouteFare(route: Route, vehicleId: VehicleCategory): number {
  const dist = route.approxDistanceKm;
  if (!dist || dist <= 0) return 0;

  const isKolkata =
    isKolkataLocation(route.originName) ||
    isKolkataLocation(route.destinationName) ||
    route.originSlug.toLowerCase() === 'kolkata' ||
    route.destinationSlug.toLowerCase() === 'kolkata' ||
    route.originSlug.toLowerCase().includes('howrah') ||
    route.destinationSlug.toLowerCase().includes('howrah');

  const requiresReturnFare = dist > 200 && !isKolkata;
  // Short-distance rental: ₹700 added for routes under 50 km
  const shortDistanceRental = dist < SHORT_DISTANCE_THRESHOLD_KM ? SHORT_DISTANCE_RENTAL_CHARGE : 0;

  if (vehicleId === 'sedan') {
    const rate = requiresReturnFare ? 14 : 21;
    const factor = requiresReturnFare ? 2 : 1;
    return Math.round(dist * rate * factor) + shortDistanceRental;
  }

  if (vehicleId === 'ertiga') {
    const rate = requiresReturnFare ? 20 : 26;
    const factor = requiresReturnFare ? 2 : 1;
    return Math.round(dist * rate * factor) + shortDistanceRental;
  }

  if (vehicleId === 'innova') {
    const rate = 35;
    const factor = requiresReturnFare ? 2 : 1;
    return Math.round(dist * rate * factor) + shortDistanceRental;
  }

  // Fallback for any other vehicle (e.g. tempo traveller)
  const rate = 28;
  const factor = requiresReturnFare ? 2 : 1;
  return Math.round(dist * rate * factor) + shortDistanceRental;
}

/** Sedan (starting) one-way fare for a route, in INR. */
export function getRouteStartingFare(route: Route): number {
  return getRouteFare(route, 'sedan');
}

/** Vehicle-wise one-way fare map for a route (vehicleId → INR). */
export function getRouteFareMap(route: Route): Record<string, number> {
  const map: Record<string, number> = {};
  for (const v of VEHICLES) {
    map[v.id] = getRouteFare(route, v.id);
  }
  return map;
}

/**
 * Resolves a route from free-text/geocoded city names (e.g. "Bokaro Steel
 * City" → Bokaro). Used by the live fare estimator so that a booking enquiry
 * between two known cities reflects the same quoted route fare as the route
 * page. Returns undefined when either name cannot be matched to a location.
 */
export function findRouteByCityNames(
  originName?: string,
  destinationName?: string
): Route | undefined {
  if (!originName || !destinationName) return undefined;

  const slugFor = (name: string): string | undefined => {
    const n = name.trim().toLowerCase();
    if (!n) return undefined;
    const match = ALL_LOCATIONS.find(
      (l) =>
        l.slug === n ||
        l.name.toLowerCase() === n ||
        n.includes(l.name.toLowerCase()) ||
        l.name.toLowerCase().includes(n)
    );
    return match?.slug;
  };

  const originSlug = slugFor(originName);
  const destinationSlug = slugFor(destinationName);
  if (!originSlug || !destinationSlug) return undefined;

  return getRouteBySlug(originSlug, destinationSlug);
}
