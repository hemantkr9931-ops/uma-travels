// ─── AUTO-GENERATED ROUTE COVERAGE ───────────────────────────────────────────
// Fills the complete required network with estimated values. Curated routes
// always win; a generated route is only created for a pair that is missing.
//
//   • Jharkhand internal mesh — every city ↔ every other Jharkhand city
//   • Non-Jharkhand cities   — bidirectional links with every Jharkhand hub
//                              (Dhanbad, Ranchi, Bokaro, Jamshedpur)
//
// Distances are estimated from city coordinates (great-circle × road factor);
// durations assume an average driving speed. Values are approximate, matching
// the disclaimer shown on every route page.

/** Great-circle distance in km between two coordinates. */
function haversineKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 6371;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}

/** Approximate road distance — great-circle distance adjusted for road routing. */
function estimateRoadKm(a: Location, b: Location): number {
  const straight = haversineKm(a.lat, a.lng, b.lat, b.lng);
  const roadFactor = straight < 30 ? 1.4 : straight < 120 ? 1.3 : 1.25;
  return Math.max(5, Math.round(straight * roadFactor));
}

/** Approximate driving duration at an average highway speed. */
function estimateDurationMin(km: number): number {
  const avgSpeed = km < 40 ? 40 : 55; // slower average on short/urban legs
  return Math.max(15, Math.round((km / avgSpeed) * 60));
}

